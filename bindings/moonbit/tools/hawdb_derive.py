#!/usr/bin/env python3
"""Strict, deterministic source-to-source generator for MoonBit HawDB records.

Input: .mbt.in with #derive.hawdb_params / #derive.hawdb_row.
Only a deliberately small, documented subset of MoonBit struct declarations
is accepted. Unknown attributes/types/field syntax fail rather than silently
generating incorrect encoders. Generated .mbt is checked in and typechecked.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ATTR = re.compile(r"#derive\.hawdb_(params|row)\s+pub\(all\)\s+struct\s+([A-Za-z_]\w*)\s*\{([^{}]*)\}", re.S)
FIELD = re.compile(r"\s*([A-Za-z_]\w*)\s*:\s*(String|Int64|Bool)\s*,?\s*")
TYPES = {
    "String": ("Text", "Text"),
    "Int64": ("Int", "Int"),
    "Bool": ("Bool", "Bool"),
}


def generate(source: str, alias: str = "hawdb") -> str:
    if not re.fullmatch(r"[A-Za-z_]\w*", alias):
        raise ValueError(f"Invalid MoonBit package alias: {alias!r}")
    prefix = f"@{alias}."
    chunks = ["// Code generated by tools/hawdb_derive.py; DO NOT EDIT.", ""]
    matches = list(ATTR.finditer(source))
    if not matches:
        raise ValueError("No supported HawDB derive struct declarations found")
    if re.sub(ATTR, "", source).strip():
        raise ValueError("Unexpected syntax outside supported derive structs")
    names: set[str] = set()
    for m in matches:
        mode, name, body = m.groups()
        if name in names:
            raise ValueError(f"Duplicate struct: {name}")
        names.add(name)
        fields = []
        for line in body.splitlines():
            if not line.strip():
                continue
            fm = FIELD.fullmatch(line)
            if fm is None:
                raise ValueError(f"Unsupported field declaration in {name}: {line!r}")
            fields.append(fm.groups())
        if not fields or len({n for n, _ in fields}) != len(fields):
            raise ValueError(f"Empty or duplicate fields in {name}")
        chunks.append(f"pub(all) struct {name} {{")
        for field, typ in fields:
            chunks.append(f"  {field} : {typ}")
        chunks += ["}", ""]
        if mode == "params":
            chunks += [f"pub impl {prefix}HawdbParams for {name} with to_params(self : {name}) -> Map[String, {prefix}Value] {{",
                       "  {"]
            for field, typ in fields:
                chunks.append(f'    "{field}": {prefix}Value::{TYPES[typ][0]}(self.{field}),')
            chunks += ["  }", "}", ""]
        else:
            chunks += [f"pub impl {prefix}HawdbRow for {name} with from_row(result : {prefix}QueryResult, index : Int) -> Result[{name}, {prefix}HawdbError] {{",
                       "  let values = result"]
            for field, typ in fields:
                chunks += [f'  let {field} = match values.get(index, "{field}") {{',
                           f"    Some({prefix}Value::{TYPES[typ][1]}(v)) => v",
                           f'    _ => return Err({prefix}HawdbError::Codec("missing or invalid column: {field}"))',
                           "  }"]
            chunks += ["  Ok({"]
            for field, _ in fields:
                chunks.append(f"    {field},")
            chunks += ["  })", "}", ""]
    return "\n".join(chunks).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--alias", default="hawdb")
    args = parser.parse_args()
    try:
        text = generate(args.source.read_text(encoding="utf-8"), alias=args.alias)
    except ValueError as ex:
        print(f"hawdb derive error: {ex}", file=sys.stderr)
        return 1
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != text:
            print(f"Generated MoonBit out of date: {args.output}", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
